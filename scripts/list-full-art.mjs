// Writes src/lib/full-art.ts: the card drawings that have a larger copy under
// public/cards/full/, so the full-screen view asks only for copies that exist.
// Usage: node scripts/list-full-art.mjs
// Run it after adding a larger copy; src/lib/art.test.ts fails while the list is out of date.

import { readdir, writeFile } from "node:fs/promises";
import { sep } from "node:path";

const FULL = "public/cards/full";
const TARGET = "src/lib/full-art.ts";

const files = (await readdir(FULL, { recursive: true }))
  .map((file) => file.split(sep).join("/"))
  .filter((file) => file.endsWith(".webp"))
  .sort();
const lines = files.map((file) => `  "${file}",`).join("\n");
await writeFile(
  TARGET,
  `// Generated by scripts/list-full-art.mjs: the card drawings with a larger copy in public/cards/full/.\nexport const FULL_ART: ReadonlySet<string> = new Set([\n${lines}\n]);\n`,
);
console.log(`${TARGET}: ${files.length} drawings with a larger copy`);
