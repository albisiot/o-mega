// Writes src/lib/motion-art.ts: the card drawings that have a looping video
// under public/cards/motion/ (same path, .mp4), so a card asks only for videos
// that exist. Usage: node scripts/list-motion-art.mjs
// Run it after adding a video; src/lib/art.test.ts fails while the list is out of date.

import { readdir, writeFile } from "node:fs/promises";
import { sep } from "node:path";

const MOTION = "public/cards/motion";
const TARGET = "src/lib/motion-art.ts";

const files = (await readdir(MOTION, { recursive: true }))
  .map((file) => file.split(sep).join("/"))
  .filter((file) => file.endsWith(".mp4"))
  .sort();
const lines = files.map((file) => `  "${file}",`).join("\n");
await writeFile(
  TARGET,
  `// Generated by scripts/list-motion-art.mjs: the card drawings with a looping video in public/cards/motion/.\nexport const MOTION_ART: ReadonlySet<string> = new Set([\n${lines}\n]);\n`,
);
console.log(`${TARGET}: ${files.length} drawings with a video`);
