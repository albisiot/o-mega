// Writes src/lib/diorama-index.ts, the list of the characters' dioramas, from the files in
// src/lib/dioramas: one per character, its builder exported as `export function name(kit: Kit)`
// under a doc comment that starts with the character's name and card code, e.g.
// "/**\n * Holdout (P057): ...". Run it after adding or renaming a diorama file.
//
//   node scripts/sync-dioramas.mjs

import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const dir = "src/lib/dioramas";
const entries = [];
for (const file of readdirSync(dir).filter((name) => name.endsWith(".ts")).sort()) {
  const text = readFileSync(join(dir, file), "utf8");
  const builder = text.match(/export function (\w+)\(kit: Kit\): Framing/);
  const card = text.match(/\/\*\*\s*\n?\s*\*?\s*([^(\n*]+?) \((P\d{3})\)/);
  if (!builder || !card) throw new Error(`${file}: no "export function name(kit: Kit): Framing" under a "/** Name (Pxxx)" comment`);
  entries.push({ code: card[2], name: card[1].trim(), file: file.replace(/\.ts$/, ""), fn: builder[1] });
}
entries.sort((a, b) => a.code.localeCompare(b.code));
const codes = new Set();
for (const entry of entries) {
  if (codes.has(entry.code)) throw new Error(`Two dioramas for ${entry.code}`);
  codes.add(entry.code);
}

const lines = entries.map(
  ({ code, name, file, fn }) =>
    `  { code: "${code}", name: ${JSON.stringify(name)}, load: () => import("@/lib/dioramas/${file}").then((module) => module.${fn}) },`,
);
const text = `// Generated by scripts/sync-dioramas.mjs from the files in src/lib/dioramas: do not edit by hand.
import type { Framing, Kit } from "@/lib/diorama-kit";

export type DioramaBuilder = (kit: Kit) => Framing;

/** Every character with a diorama; each diorama's code is downloaded only when it is opened. */
export const DIORAMAS: { code: string; name: string; load: () => Promise<DioramaBuilder> }[] = [
${lines.join("\n")}
];

const CODES = new Set(DIORAMAS.map((diorama) => diorama.code));

/** Whether a card has a diorama. */
export function hasCardDiorama(code: string): boolean {
  return CODES.has(code);
}
`;
writeFileSync("src/lib/diorama-index.ts", text);
console.log(`src/lib/diorama-index.ts: ${entries.length} dioramas`);
