// Copies the rules engine into supabase/functions/_shared/game-engine so the
// Edge Functions bundle is self-contained. packages/game-engine stays the only
// source: the copy is generated (and git-ignored) on every deploy.
// Usage: node scripts/sync-engine.mjs (run by npm run functions:deploy)

import { mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const SOURCE = join("packages", "game-engine", "src");
const TARGET = join("supabase", "functions", "_shared", "game-engine");
const HEADER = "// GENERATED by scripts/sync-engine.mjs from packages/game-engine. Do not edit.\n";

rmSync(TARGET, { recursive: true, force: true });
mkdirSync(TARGET, { recursive: true });

const files = readdirSync(SOURCE).filter(
  (name) => name.endsWith(".ts") && !name.endsWith(".test.ts") && name !== "test-fixtures.ts",
);
for (const name of files) {
  writeFileSync(join(TARGET, name), HEADER + readFileSync(join(SOURCE, name), "utf8"));
}
console.log(`game-engine synced to ${TARGET} (${files.length} files)`);
